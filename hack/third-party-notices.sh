# Rewrite the Go module tables at the end of THIRD_PARTY_NOTICES.md from the
# modules linked into the controller and into mock-dpuagent. Everything above
# the marker line is maintained by hand and kept as is.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=hack/dpuagent/checkout.sh
source "$ROOT/hack/dpuagent/checkout.sh"
GO_LICENSES="${GO_LICENSES:?GO_LICENSES must point at the go-licenses binary}"
CACHE="${DPUAGENT_CACHE_DIR:-$ROOT/.cache/dpuagent}"
NOTICES="${THIRD_PARTY_NOTICES:-$ROOT/THIRD_PARTY_NOTICES.md}"
TEMPLATE="$ROOT/hack/third-party-notices.tpl"
MARKER='<!-- Generated by make generate-third-party-notices. Do not edit below this line. -->'

if ! grep -qxF "$MARKER" "$NOTICES"; then
	echo "$NOTICES has no marker line: $MARKER" >&2
	exit 1
fi

dpuagent_checkout "$ROOT" "$CACHE"

log="$(mktemp)"
out="$(mktemp)"
trap 'rm -f "$log" "$out" "$NOTICES.tmp"' EXIT

# report DIR IGNORE PACKAGE prints one table row per library PACKAGE links.
# Both binaries only ship for linux/amd64, so scan for that platform rather
# than the host's. go-licenses recognizes the standard library by the GOROOT
# it was built with, so the go list it runs must not switch toolchains.
report() {
	if ! (cd "$1" && GOTOOLCHAIN=local GOOS=linux GOARCH=amd64 \
		"$GO_LICENSES" report --template "$TEMPLATE" --ignore "$2" "$3") \
		> "$out" 2> "$log"; then
		cat "$log" >&2
		exit 1
	fi
	LC_ALL=C sort "$out"
}

table() {
	printf '\n## %s\n\n' "$1"
	printf '| Library | Version | License |\n| --- | --- | --- |\n'
	report "$2" "$3" "$4"
}

{
	awk -v marker="$MARKER" '{ print } $0 == marker { exit }' "$NOTICES"
	table "Go modules in the controller" \
		"$ROOT" github.com/NVIDIA/doca-platform-scale-sim ./cmd/...
	table "Go modules in mock-dpuagent" \
		"$CACHE" github.com/nvidia/doca-platform ./test/mock/dpuagent
} > "$NOTICES.tmp"
mv "$NOTICES.tmp" "$NOTICES"
